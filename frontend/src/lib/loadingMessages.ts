export function pickLoadingMessage(rng: () => number = Math.random): string {
  const index = Math.floor(rng() * LOADING_MESSAGES.length);
  return LOADING_MESSAGES[Math.min(Math.max(index, 0), LOADING_MESSAGES.length - 1)] ?? LOADING_MESSAGES[0];
}
